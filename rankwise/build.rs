//! Emits straight-line comparator networks for small stacks.
//!
//! Each network is a function over `n` local variables, so after inlining into a
//! `#[target_feature]` kernel LLVM keeps the whole stack in vector registers instead of
//! spilling a buffer to L1 after every compare-exchange (the prototype's bottleneck).

#![allow(clippy::needless_range_loop)]

use std::fmt::Write as _;
use std::path::PathBuf;

#[allow(dead_code)]
mod netgen {
    include!("src/netgen.rs");
}

/// Largest stack depth that gets an unrolled network.
const MAX_UNROLL: usize = 32;

fn emit(out: &mut String, name: &str, n: usize, net: &[(u16, u16)]) {
    // On WebAssembly each network stays its own function: simd128 is module-wide, and small
    // functions reach the engine's optimizing tier sooner (see docs/wasm.md).
    writeln!(out, "#[cfg_attr(not(target_family = \"wasm\"), inline(always))]").unwrap();
    writeln!(out, "#[cfg_attr(target_family = \"wasm\", inline(never))]").unwrap();
    writeln!(out, "#[allow(unused_mut, clippy::all)]").unwrap();
    writeln!(out, "pub(crate) unsafe fn {name}<V: crate::simd::Vector>(b: *mut V) {{").unwrap();
    let mut used = vec![false; n];
    for &(a, c) in net {
        used[a as usize] = true;
        used[c as usize] = true;
    }
    for i in 0..n {
        if used[i] {
            writeln!(out, "    let mut x{i} = *b.add({i});").unwrap();
        }
    }
    for &(a, c) in net {
        writeln!(out, "    let t = x{a}; x{a} = t.min(x{c}); x{c} = t.max(x{c});").unwrap();
    }
    for i in 0..n {
        if used[i] {
            writeln!(out, "    *b.add({i}) = x{i};").unwrap();
        }
    }
    writeln!(out, "}}\n").unwrap();
}

fn main() {
    println!("cargo:rerun-if-changed=src/netgen.rs");
    println!("cargo:rerun-if-changed=build.rs");
    let mut out = String::new();
    writeln!(out, "// @generated by build.rs: do not edit.\n").unwrap();
    writeln!(out, "pub(crate) const MAX_UNROLL: usize = {MAX_UNROLL};\n").unwrap();
    for n in 2..=MAX_UNROLL {
        let full = netgen::batcher(n);
        emit(&mut out, &format!("sort_{n}"), n, &full);
        let med = netgen::prune(&full, n, &netgen::median_ranks(n));
        emit(&mut out, &format!("median_{n}"), n, &med);
    }
    // Dispatchers. `kind` 0 = full sort, 1 = median-pruned.
    writeln!(out, "#[inline(always)]").unwrap();
    writeln!(out, "pub(crate) unsafe fn unrolled<V: crate::simd::Vector>(b: *mut V, n: usize, kind: u8) {{").unwrap();
    writeln!(out, "    match (kind, n) {{").unwrap();
    for n in 2..=MAX_UNROLL {
        writeln!(out, "        (0, {n}) => sort_{n}(b),").unwrap();
        writeln!(out, "        (_, {n}) => median_{n}(b),").unwrap();
    }
    writeln!(out, "        _ => {{}}").unwrap();
    writeln!(out, "    }}\n}}").unwrap();

    let dst = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("unrolled.rs");
    std::fs::write(dst, out).unwrap();
}
